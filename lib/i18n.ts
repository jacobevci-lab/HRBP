const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, tr };

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "tr";
}

export function translate(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>) {
  let value = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (!vars) return value;
  for (const [name, replacement] of Object.entries(vars)) {
    value = value.replaceAll(`{${name}}`, String(replacement));
  }
  return value;
}

export type { TranslationKey };
